import datetime

from . import __version__
from .summary import family_rows, focus_families, overall_row, recent_games


def md_text(text):
    return str(text).replace("|", "\\|")


def sorted_family_rows(games):
    rows = family_rows(games)
    rows.sort(
        key=lambda row: (
            row["score"] if row["score"] is not None else 999.0,
            -row["games"],
            row["family"],
        )
    )
    return rows


def family_table_lines(games):
    lines = [
        "| Opening family | Games | W | D | L | no result | Score |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in sorted_family_rows(games):
        score = "{:.0f}%".format(row["score"]) if row["score"] is not None else "-"
        lines.append(
            "| {} | {} | {} | {} | {} | {} | {} |".format(
                md_text(row["family"]),
                row["games"],
                row["wins"],
                row["draws"],
                row["losses"],
                row["unknown"],
                score,
            )
        )
    return lines


def focus_lines(games):
    focus = focus_families(games)
    if not focus:
        return ["No focus pick yet: a family needs 2+ decided games before the card flags it."]
    lines = []
    for index, row in enumerate(focus, start=1):
        lines.append(
            "{}. **{}** - {:.0f}% score over {} game{} ({} W, {} D, {} L).".format(
                index,
                row["family"],
                row["score"],
                row["games"],
                "" if row["games"] == 1 else "s",
                row["wins"],
                row["draws"],
                row["losses"],
            )
        )
    return lines


def drift_lines(drift):
    if drift is None:
        return ["Not checked. Run `chess-opening-journal drift` when you want it."]
    off_book = drift.get("off_book", [])
    if not off_book:
        if drift.get("uncovered"):
            return ["All games stayed on your known lines in the families you cover."]
        return [
            "No known lines registered yet;"
            " add some with `repertoire add --pgn FILE --side white` (or black)."
        ]
    lines = ["{} game{} wandered off your known lines:".format(len(off_book), "" if len(off_book) == 1 else "s")]
    for row in off_book[:3]:
        game = row["game"]
        played = row.get("played")
        expected = row.get("expected")
        continuation = row.get("continuation")
        played_text = played if played else "(game shorter than your line)"
        expected_text = expected if expected else "(line already done)"
        tail_text = continuation if continuation else "(your line ends there)"
        lines.append(
            "- `{}` {} after `{}`, you played `{}` but your line continues with `{}` and later `{}`".format(
                game.get("id"),
                md_text(row["family"]),
                md_text(row["matched_prefix"]) or "(start)",
                md_text(played_text),
                md_text(expected_text),
                md_text(tail_text),
            )
        )
    return lines


def review_queue_lines(games):
    recent = recent_games(games, 3)
    if not recent:
        return ["(no games logged)"]
    lines = []
    for game in recent:
        note = (game.get("note") or "").replace("|", "\\|")
        confidence = game.get("confidence")
        pieces = [
            game.get("date") or "?",
            "`{}`".format(game.get("id") or "?"),
            "{}".format(game.get("opening_family") or "?"),
            "{} as {}".format(game.get("result") or "?", game.get("you_color") or "color?"),
            "{} plies".format(game.get("ply_count", len(game.get("moves", [])))),
            "effort {}/5".format(confidence) if confidence else "",
            'note: "{}"'.format(note) if note else "",
        ]
        pieces = [piece for piece in pieces if piece]
        lines.append("- " + " - ".join(pieces))
    return lines
    return lines


def render_practice_card(journal, drift, today=None):
    games = journal.get("games", [])
    repertoire = journal.get("repertoire", [])
    today = today or datetime.date.today().isoformat()

    title = "# Practice Focus Card"
    generated_note = (
        "Generated by chess-opening-journal v{} on {} - '{}' - no engines, no network.".format(
            __version__, today, journal.get("journal_name") or "local JSON journal"
        )
    )

    produced = [title, "", "_" + generated_note + "_", ""]

    if not games:
        produced.append("There are no logged games yet, so there is nothing to focus on.")
        produced.append("* Use `chess-opening-journal log --family \"Sicilian Defense\" --result win`")
        produced.append("* or `chess-opening-journal add game.pgn --player \"Your Name\"`")
        produced.append("* to log games and get a card next time.")
        return "\n".join(produced)

    overall = overall_row(games)
    with_lines = len({(line.get("family"), line.get("side")) for line in repertoire})
    produced.append("## Snapshot")
    produced.append("")
    produced.append(
        "- Games logged: {} ({} win / {} draw / {} loss / {} unrecorded result)".format(
            overall["games"],
            overall["wins"],
            overall["draws"],
            overall["losses"],
            overall["unknown"],
        )
    )
    if overall["score"] is not None:
        produced.append(
            "- Decided score: {:.0f}% of the decisively recorded game results.".format(overall["score"])
        )
    produced.append(
        "- Repertoire: {} known line{} spread over {} family/side pair{}.".format(
            len(repertoire),
            "" if len(repertoire) == 1 else "s",
            with_lines,
            "" if with_lines == 1 else "s",
        )
    )
    produced.append("")

    produced.append("## Openings by family")
    produced.append("")
    produced.extend(family_table_lines(games))
    produced.append("")

    produced.append("## What to focus on next")
    produced.append("")
    produced.extend(focus_lines(games))
    produced.append("")

    produced.append("## Book drift (if checked)")
    produced.append("")
    produced.extend(drift_lines(drift))
    produced.append("")

    produced.append("## Review queue (recent games)")
    produced.append("")
    produced.extend(review_queue_lines(games))
    produced.append("")

    produced.append("---")
    produced.append("_Chess practice plan only (no engines, no accounts); you still play the games._")
    return "\n".join(produced)
